def estimate_recipe_kcal(ingredients: list[dict], base_servings: int = 2) -> int:
    """Estimate calories per serving from ingredient quantities."""
    total_kcal = 0.0
    for line in ingredients:
        iid = str(line.get("ingredient_id") or line.get("id") or "")
        qty = float(line.get("quantity") or 0)
        total_kcal += qty * INGREDIENT_KCAL_PER_UNIT.get(iid, 1.0)
    per_serving = round(total_kcal / max(1, base_servings))
    return max(80, min(1500, per_serving))


